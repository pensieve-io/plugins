import { CliError } from "./errors.js";

/**
 * Entries from `list_trees` text, e.g.
 * - `owner/repo@prod` — Repo (repository, tree id `…`, root `page:9`, https://…, status completed, processed abc123)
 */
export function parseTreeList(text) {
  const trees = [];
  for (const line of text.split("\n")) {
    const match = line.match(/^- `([^`]+)`(.*)$/);
    if (!match) continue;
    const rest = match[2];
    trees.push({
      selector: match[1],
      rootPageId: Number(rest.match(/root `page:(\d+)`/)?.[1]) || null,
      processed: rest.match(/\bprocessed ([0-9a-f]{7,40})\b/i)?.[1] || null,
      detected: rest.match(/\bdetected ([0-9a-f]{7,40})\b/i)?.[1] || null,
      status: rest.match(/\bstatus ([\w-]+)/)?.[1] || null,
    });
  }
  return trees;
}

/** The repository tree for `repo`: an explicit selector, else `owner/repo@…`. */
export function selectTree(trees, { repo, selector, branch }) {
  if (selector) {
    const found = trees.find((t) => t.selector.toLowerCase() === selector.toLowerCase());
    if (!found) throw new CliError(`No tree named \`${selector}\`. Available: ${list(trees)}`);
    return found;
  }
  if (!repo) throw new CliError("Could not tell which repository this is; pass --tree.");
  const prefix = `${repo.toLowerCase()}@`;
  const matches = trees.filter((t) => t.selector.toLowerCase().startsWith(prefix));
  if (matches.length === 1) return matches[0];
  if (!matches.length) {
    throw new CliError(
      `No Pensieve repository tree for ${repo} in this context. Available: ${list(trees)}. ` +
        "Connect the repository in Pensieve, or pass --tree / --context.",
    );
  }
  const onBranch = matches.find((t) => t.selector.slice(prefix.length) === branch);
  if (onBranch) return onBranch;
  throw new CliError(`Several trees match ${repo}: ${list(matches)}. Pass --tree.`);
}

const list = (trees) => (trees.length ? trees.map((t) => t.selector).join(", ") : "none");

/**
 * Pages from a `get_tree` outline. Each nesting level is four characters of
 * `│   `, `    `, `├── ` or `└── `; a line reads `slug "Title" (page:ID)`.
 */
export function parseOutline(text) {
  const pages = [];
  let truncated = false;
  for (const line of text.split("\n")) {
    const match = line.match(/^((?:│ {3}| {4}|├── |└── )*)(\S+) "(.*)" \(page:(\d+)\)(.*)$/);
    if (!match) continue;
    if (/\(\+\d+ below/.test(match[5])) truncated = true;
    pages.push({ level: match[1].length / 4, slug: match[2], title: match[3], id: Number(match[4]) });
  }
  return { pages, truncated };
}

/** A filesystem-safe name: no separators, dots or traversal can survive. */
export function slugify(value, fallback = "page") {
  const slug = String(value || "")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80)
    .replace(/-+$/, "");
  return slug || fallback;
}

/**
 * Relative Markdown paths mirroring the hierarchy: the root Page sits at the
 * top beside its children, and each Page's children live in a directory
 * named like its file. Names are unique per directory and never `index`.
 */
export function planPaths(pages) {
  const used = new Map();
  const unique = (dir, name) => {
    const taken = used.get(dir) || new Set(dir ? [] : ["index"]);
    used.set(dir, taken);
    let candidate = name;
    for (let n = 2; taken.has(candidate); n++) candidate = `${name}-${n}`;
    taken.add(candidate);
    return candidate;
  };
  const stack = [];
  return pages.map((page) => {
    stack.length = Math.min(stack.length, page.level);
    const dir = page.level === 0 ? "" : (stack[page.level - 1] ?? "");
    const name = unique(dir, slugify(page.slug || page.title, `page-${page.id}`));
    const childDir = page.level === 0 ? "" : dir ? `${dir}/${name}` : name;
    stack[page.level] = childDir;
    return { ...page, path: `${dir ? `${dir}/` : ""}${name}.md` };
  });
}

export const INDEX_MARKER = "<!-- generated by pensieve docs pull; safe to delete -->";

export function renderIndex({ tree, repo, contextId, head, pages, total, truncated, pulledAt }) {
  const stale = head && tree.processed && !sameRevision(head, tree.processed);
  const lines = [
    INDEX_MARKER,
    `# Pensieve docs${repo ? `: ${repo}` : ""}`,
    "",
    `Generated from the Pensieve tree \`${tree.selector}\`${contextId ? ` (context ${contextId})` : ""} on ${pulledAt}.`,
    "These Pages are generated from the code Pensieve last processed and may lag it; verify against source.",
    "",
    `- Processed revision: ${tree.processed ? `\`${tree.processed}\`` : "unknown"}`,
    `- Local HEAD when pulled: ${head ? `\`${head}\`` : "unknown"}`,
  ];
  if (stale) lines.push("- **Stale:** the tree describes a different revision from local HEAD.");
  if (pages.length < total) lines.push(`- Pulled ${pages.length} of ${total} Pages (page cap reached).`);
  if (truncated) lines.push("- Some branches are deeper than this pull reaches; see Pensieve for the rest.");
  lines.push("", "## Pages", "");
  for (const page of pages) {
    lines.push(`${"  ".repeat(page.level)}- [${page.title.replace(/[[\]]/g, "\\$&")}](${page.path})`);
  }
  return `${lines.join("\n")}\n`;
}

export const sameRevision = (a, b) =>
  !!a && !!b && (a.toLowerCase().startsWith(b.toLowerCase()) || b.toLowerCase().startsWith(a.toLowerCase()));
